-- ICT371 QUESTION 10: SCHOLARSHIP APPLICATION ASSESSMENT
-- Eligibility: age 18-25 inclusive, income <= K3,000, average mark >= 70.

DROP VIEW IF EXISTS v_approved_applicants CASCADE;
DROP TABLE IF EXISTS decision_audit, applications, students CASCADE;

CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL
);

CREATE TABLE applications (
    application_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(student_id),
    age_at_application INTEGER NOT NULL CHECK (age_at_application > 0),
    monthly_income NUMERIC(12,2) NOT NULL CHECK (monthly_income >= 0),
    average_mark NUMERIC(5,2) NOT NULL CHECK (average_mark BETWEEN 0 AND 100),
    submitted_on DATE NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE decision_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id INTEGER NOT NULL REFERENCES applications(application_id),
    old_status VARCHAR(10) NOT NULL,
    new_status VARCHAR(10) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- (b) Eligibility function with validation.
CREATE OR REPLACE FUNCTION fn_scholarship_eligible(
    p_age INTEGER, p_income NUMERIC, p_mark NUMERIC
)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
BEGIN
    IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN
        RAISE EXCEPTION 'Age, income and mark cannot be NULL';
    END IF;
    IF p_age <= 0 OR p_income < 0 OR p_mark < 0 OR p_mark > 100 THEN
        RAISE EXCEPTION 'Invalid age, income or mark';
    END IF;

    RETURN p_age BETWEEN 18 AND 25
       AND p_income <= 3000
       AND p_mark >= 70;
END;
$$;

-- (d) Audit only actual status changes.
CREATE OR REPLACE FUNCTION fn_audit_application_status()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO decision_audit(application_id, old_status, new_status)
        VALUES (NEW.application_id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_application_status_audit
AFTER UPDATE OF status ON applications
FOR EACH ROW EXECUTE FUNCTION fn_audit_application_status();

-- (c) Assess only an existing PENDING application.
CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id INTEGER)
LANGUAGE plpgsql AS $$
DECLARE
    v_age INTEGER; v_income NUMERIC(12,2); v_mark NUMERIC(5,2); v_status VARCHAR(10);
    v_new_status VARCHAR(10);
BEGIN
    SELECT age_at_application, monthly_income, average_mark, status
    INTO v_age, v_income, v_mark, v_status
    FROM applications
    WHERE application_id = p_application_id
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application ID: %', p_application_id; END IF;
    IF v_status <> 'PENDING' THEN
        RAISE EXCEPTION 'Application % has already been assessed', p_application_id;
    END IF;

    IF fn_scholarship_eligible(v_age, v_income, v_mark) THEN
        v_new_status := 'APPROVED';
    ELSE
        v_new_status := 'REJECTED';
    END IF;

    UPDATE applications
    SET status = v_new_status
    WHERE application_id = p_application_id;
END;
$$;

